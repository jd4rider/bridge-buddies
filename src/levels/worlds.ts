import type { MaterialId, VehicleId } from '../core/types'

export type Weather = 'clear' | 'wind' | 'rain' | 'snow' | 'storm'

export interface WorldSpec {
  id: number
  name: string
  tagline: string
  /** Palette: sky gradient and fog, terrain, water, foliage. */
  sky: string
  horizon: string
  fog: string
  ground: string
  groundDark: string
  water: string
  foliage: string
  rock: string
  materials: MaterialId[]
  vehicles: VehicleId[]
  /** Gap range in metres, from the first level of the world to the last. */
  gap: [number, number]
  /** Base lateral wind in m/s. */
  wind: number
  weather: Weather
  mechanic: string
}

